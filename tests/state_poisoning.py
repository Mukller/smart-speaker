"""Регресс: одна неудачная команда не должна убивать все плагины.

Плагин таймера на фразе «поставь таймер на чай» не разбирает остаток и
оставляет в ядре незаконченный вопрос БЕЗ СРОКА. После этого ядро считало
каждую следующую фразу продолжением старой команды и отвечало «Что после
таймер?» на всё подряд, включая погоду, - до перезапуска контейнера.

Порядок в этом тесте и есть суть: сначала погода, потом отравляющая команда,
потом снова погода. Если снова «Что после таймер?» - баг жив.

Прогон: python tests/state_poisoning.py
"""

import json
import time
import urllib.parse
import urllib.request

API = 'https://antonpetnitsky.com/kolonka/api'


def ask(q, timeout=180):
    url = API + '/sendTxtCmd?cmd=' + urllib.parse.quote(q)
    t0 = time.time()
    with urllib.request.urlopen(url, timeout=timeout) as r:
        d = json.load(r)
    return d.get('source'), (d.get('restxt') or '').strip(), time.time() - t0


# Порядок важен: сначала погода без ничего, потом таймер, потом снова погода.
plan = (
    ('какая сейчас погода', 'погода сразу'),
    ('поставь таймер на 5 минут', 'таймер'),
    ('какая сейчас погода', 'погода после таймера'),
    ('поставь таймер на чай', 'таймер на чай'),
    ('какая сейчас погода', 'погода после неудачного таймера'),
    ('какая сейчас погода', 'погода ещё раз'),
)

for q, note in plan:
    src, txt, dt = ask(q)
    print('%-24s [%-7s] %5.1f с  %s' % (note, src, dt, txt[:48]))